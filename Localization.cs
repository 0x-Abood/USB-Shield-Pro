        public static string Get(string key)
        {
            Dictionary<string, string> dict = Current == Language.Arabic ? Ar : En;
            if (dict.ContainsKey(key)) return dict[key];
            if (En.ContainsKey(key)) return En[key];
            return key;
        }

        public static string Get(string key, params object[] args)
        {
            return string.Format(Get(key), args);
        }

        public static bool IsRtl
        {
            get { return Current == Language.Arabic; }
        }

        public static RightToLeft RtlValue
        {
            get { return Current == Language.Arabic ? RightToLeft.Yes : RightToLeft.No; }
        }

        public static void Toggle()
        {
            Current = Current == Language.English ? Language.Arabic : Language.English;
        }
